drop policy if exists "site can create whatsapp orders" on public.orders;
create policy "site can create whatsapp orders" on public.orders
for insert to anon, authenticated
with check (
  reference ~ '^ZW(-GIFT)?-[0-9]{10}(-[A-Z0-9]{4})?$'
  and kind in ('order','gift')
  and status='new'
  and total>=0
  and case when jsonb_typeof(items)='array'
    then jsonb_array_length(items) between 1 and 100
    else false end
  and coalesce(char_length(customer_name),0)<=120
  and coalesce(char_length(area),0)<=180
  and coalesce(char_length(notes),0)<=800
);

