-- Browser code must use only the publishable key. Never expose secret/service-role keys.

create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  label text not null default 'Owner',
  created_at timestamptz not null default now()
);

create table if not exists public.product_overrides (
  product_id text primary key,
  action text not null default 'upsert' check (action in ('upsert','hide')),
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.site_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('page_view','product_view','add_to_cart','whatsapp_click','search')),
  page_path text not null check (char_length(page_path) <= 300),
  session_id text check (char_length(session_id) <= 80),
  referrer_host text check (char_length(referrer_host) <= 180),
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  reference text primary key check (reference ~ '^ZW(-GIFT)?-[0-9]{10}(-[A-Z0-9]{4})?$'),
  kind text not null default 'order' check (kind in ('order','gift')),
  status text not null default 'new' check (status in ('new','confirmed','preparing','out_for_delivery','delivered','cancelled')),
  customer_name text check (coalesce(char_length(customer_name),0) <= 120),
  area text check (coalesce(char_length(area),0) <= 180),
  notes text check (coalesce(char_length(notes),0) <= 800),
  items jsonb not null default '[]'::jsonb,
  total numeric(10,2) not null default 0 check (total >= 0),
  currency text not null default 'USD' check (currency = 'USD'),
  language text not null default 'en' check (language in ('en','ar')),
  extra jsonb not null default '{}'::jsonb,
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  confirmed_at timestamptz,
  out_for_delivery_at timestamptz,
  delivered_at timestamptz,
  cancelled_at timestamptz
);

create table if not exists public.admin_activity (
  id bigint generated by default as identity primary key,
  actor uuid not null references auth.users(id),
  action text not null check (char_length(action) <= 120),
  target_type text check (char_length(target_type) <= 80),
  target_id text check (char_length(target_id) <= 180),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists orders_submitted_at_idx on public.orders (submitted_at desc);
create index if not exists orders_status_idx on public.orders (status, submitted_at desc);
create index if not exists admin_activity_actor_idx on public.admin_activity(actor);
create index if not exists product_overrides_updated_by_idx on public.product_overrides(updated_by);
create index if not exists site_settings_updated_by_idx on public.site_settings(updated_by);

alter table public.admin_users enable row level security;
